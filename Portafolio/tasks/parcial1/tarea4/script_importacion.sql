-- ============================================
-- CREAR TABLAS
-- ============================================

-- Tabla de Alumnos
CREATE TABLE alumnos (
    matricula INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    grado VARCHAR(20) NOT NULL,
    email VARCHAR(100) UNIQUE,
    fecha_inscripcion TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Tabla de Libros
CREATE TABLE libros (
    id_libro INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(100) NOT NULL,
    autor VARCHAR(100) NOT NULL,
    anio_publicacion INTEGER NOT NULL,
    isbn VARCHAR(13) UNIQUE,
    cantidad_disponible INTEGER DEFAULT 1
);

-- Tabla de Categorías
CREATE TABLE categorias (
    id_categoria INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL UNIQUE,
    descripcion TEXT
);

-- Tabla de relación entre Libros y Categorías
CREATE TABLE libro_categoria (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_libro INTEGER NOT NULL,
    id_categoria INTEGER NOT NULL,
    FOREIGN KEY (id_libro) REFERENCES libros(id_libro) ON DELETE CASCADE,
    FOREIGN KEY (id_categoria) REFERENCES categorias(id_categoria) ON DELETE CASCADE,
    UNIQUE(id_libro, id_categoria)
);

-- Tabla de Préstamos
CREATE TABLE prestamos (
    id_prestamo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricula INTEGER NOT NULL,
    id_libro INTEGER NOT NULL,
    fecha_prestamo DATE NOT NULL,
    fecha_devolucion DATE,
    estado VARCHAR(20) DEFAULT 'activo',
    FOREIGN KEY (matricula) REFERENCES alumnos(matricula) ON DELETE CASCADE,
    FOREIGN KEY (id_libro) REFERENCES libros(id_libro) ON DELETE CASCADE
);

-- ============================================
-- CREAR ÍNDICES
-- ============================================

CREATE INDEX idx_alumnos_email ON alumnos(email);
CREATE INDEX idx_alumnos_grado ON alumnos(grado);
CREATE INDEX idx_libros_autor ON libros(autor);
CREATE INDEX idx_libros_isbn ON libros(isbn);
CREATE INDEX idx_prestamos_alumno ON prestamos(matricula);
CREATE INDEX idx_prestamos_libro ON prestamos(id_libro);
CREATE INDEX idx_prestamos_estado ON prestamos(estado);

