-- CONSULTAS DE VALIDACIÓN
-- ============================================

-- Contar registros en cada tabla
SELECT 'alumnos' as tabla, COUNT(*) as registros FROM alumnos
UNION ALL
SELECT 'libros', COUNT(*) FROM libros
UNION ALL
SELECT 'categorias', COUNT(*) FROM categorias
UNION ALL
SELECT 'prestamos', COUNT(*) FROM prestamos;

-- Libros con sus categorías
SELECT l.titulo, l.autor, string_agg(c.nombre, ', ') as categorias
FROM libros l
LEFT JOIN libro_categoria lc ON l.id_libro = lc.id_libro
LEFT JOIN categorias c ON lc.id_categoria = c.id_categoria
GROUP BY l.id_libro, l.titulo, l.autor
ORDER BY l.titulo;

-- Préstamos activos
SELECT a.nombre, l.titulo, p.fecha_prestamo
FROM prestamos p
JOIN alumnos a ON p.matricula = a.matricula
JOIN libros l ON p.id_libro = l.id_libro
WHERE p.estado = 'activo'
ORDER BY p.fecha_prestamo DESC;

-- Alumnos con más préstamos
SELECT a.nombre, COUNT(p.id_prestamo) as total_prestamos
FROM alumnos a
LEFT JOIN prestamos p ON a.matricula = p.matricula
GROUP BY a.matricula, a.nombre
ORDER BY total_prestamos DESC;

-- Libro más solicitado
SELECT l.titulo, COUNT(p.id_prestamo) as veces_prestado
FROM libros l
LEFT JOIN prestamos p ON l.id_libro = p.id_libro
GROUP BY l.id_libro, l.titulo
ORDER BY veces_prestado DESC
LIMIT 5;
